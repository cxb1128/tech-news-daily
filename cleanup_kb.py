def write_page_safe(doc_id: str, title: str, content: str, max_retries: int = 3) -> bool:
    """安全写入页面，失败自动重试"""
    content = content.strip()

    for attempt in range(max_retries):
        try:
            client.update_doc_content(doc_id, content)
            if attempt > 0:
                print(f"   🔄 第 {attempt+1} 次重试成功")
            return True
        except Exception as e:
            print(f"   ⚠️  第 {attempt+1} 次写入失败: {e}")
            if attempt < max_retries - 1:
                time.sleep(2)
    return False


def verify_page(doc_id: str, title: str, min_chars: int = 300) -> bool:
    """验证页面内容完整"""
    try:
        content = client.get_doc_content(doc_id)
        length = len(content)
        status = "✅" if length >= min_chars else "⚠️"
        print(f"   {status} 实际长度: {length} 字符 (最低要求: {min_chars})")
        if length < min_chars:
            print(f"   ❌ 内容可能被截断，需要检查")
            return False
        return True
    except Exception as e:
        print(f"   ❌ 验证失败: {e}")
        return False


